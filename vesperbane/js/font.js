// cache: color -> canvas strip of all glyphs
const _fontCache = new Map();
const _fontOrder = Object.keys(FONT);

function _fontStrip(color) {
  let strip = _fontCache.get(color);
  if (strip) return strip;
  const c = document.createElement('canvas');
  c.width = _fontOrder.length * FONT_W;
  c.height = FONT_H;
  const g = c.getContext('2d');
  g.fillStyle = color;
  _fontOrder.forEach((ch, i) => {
    const rows = FONT[ch];
    for (let y = 0; y < FONT_H; y++)
      for (let x = 0; x < FONT_W; x++)
        if (rows[y][x] === '#') g.fillRect(i * FONT_W + x, y, 1, 1);
  });
  strip = { canvas: c, index: new Map(_fontOrder.map((ch, i) => [ch, i])) };
  _fontCache.set(color, strip);
  return strip;
}

// draws text; scale is integer pixel scale. returns pixel width drawn.
function drawText(ctx, text, x, y, scale, color) {
  scale = scale || 1;
  color = color || '#e8e4f0';
  const strip = _fontStrip(color);
  text = String(text).toUpperCase();
  let cx = Math.round(x);
  for (const ch of text) {
    const i = strip.index.get(ch);
    if (i !== undefined) {
      ctx.drawImage(strip.canvas, i * FONT_W, 0, FONT_W, FONT_H,
        cx, Math.round(y), FONT_W * scale, FONT_H * scale);
    }
    cx += (FONT_W + 1) * scale;
  }
  return cx - x;
}

function textWidth(text, scale) {
  return String(text).length * (FONT_W + 1) * (scale || 1) - (scale || 1);
}

function drawTextCentered(ctx, text, cx, y, scale, color) {
  drawText(ctx, text, cx - textWidth(text, scale) / 2, y, scale, color);
}

// text with a 1px drop shadow — main UI style
function drawTextShadow(ctx, text, x, y, scale, color, shadow) {
  drawText(ctx, text, x + scale, y + scale, scale, shadow || '#0a0a14');
  drawText(ctx, text, x, y, scale, color);
}

function drawTextShadowCentered(ctx, text, cx, y, scale, color, shadow) {
  const x = cx - textWidth(text, scale) / 2;
  drawTextShadow(ctx, text, x, y, scale, color, shadow);
}
